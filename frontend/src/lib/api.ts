const API_BASE = (
  process.env.NEXT_PUBLIC_API_URL || "https://mybiotwin.runasp.net"
).replace(/\/$/, "");

type TokenGetter = () => Promise<string | null>;
let globalTokenGetter: TokenGetter | null = null;
let globalClerkUserId: string | null = null;

/**
 * Configure the global token provider from Clerk's useAuth hook.
 */
export function configureApiClient(getter: TokenGetter, clerkUserId?: string | null) {
  globalTokenGetter = getter;
  if (clerkUserId) {
    globalClerkUserId = clerkUserId;
  }
}

/**
 * Custom error class capturing backend HTTP status and ProblemDetails.
 */
export class ApiError extends Error {
  status: number;
  data: unknown;

  constructor(status: number, message: string, data?: unknown) {
    super(message);
    this.name = "ApiError";
    this.status = status;
    this.data = data;
  }
}

/**
 * Performs an authenticated fetch against the .NET Minimal API backend.
 * Automatically injects Clerk Bearer token and dev X-User-Id header.
 */
export async function fetchWithAuth<T>(
  endpoint: string,
  options: RequestInit = {}
): Promise<T> {
  const url = `${API_BASE}${endpoint.startsWith("/") ? "" : "/"}${endpoint}`;

  let token: string | null = null;
  if (globalTokenGetter) {
    try {
      token = await globalTokenGetter();
    } catch {
      // Continue without token if retrieval fails
    }
  }

  // Fallback to window.Clerk if available
  if (!token && typeof window !== "undefined" && (window as unknown as { Clerk?: { session?: { getToken: () => Promise<string> } } }).Clerk?.session) {
    try {
      token = await (window as unknown as { Clerk: { session: { getToken: () => Promise<string> } } }).Clerk.session.getToken();
    } catch {
      // Fallback
    }
  }

  const headers = new Headers(options.headers || {});
  if (!headers.has("Content-Type") && !(options.body instanceof FormData)) {
    headers.set("Content-Type", "application/json");
  }

  if (token) {
    headers.set("Authorization", `Bearer ${token}`);
  }

  if (globalClerkUserId) {
    headers.set("X-User-Id", globalClerkUserId);
  }

  const response = await fetch(url, {
    ...options,
    headers,
  });

  if (!response.ok) {
    let errorDetail = `Request failed with status ${response.status}`;
    let data: unknown = null;
    try {
      data = await response.json();
      if (data && typeof data === "object") {
        const d = data as { detail?: string; title?: string; message?: string };
        errorDetail = d.detail || d.message || d.title || errorDetail;
      }
    } catch {
      // Not JSON
    }
    throw new ApiError(response.status, errorDetail, data);
  }

  if (response.status === 204) {
    return null as T;
  }

  return (await response.json()) as T;
}

