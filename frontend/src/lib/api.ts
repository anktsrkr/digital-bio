/**
 * Downloads the ATS-compliant PDF generated by QuestPDF.
 */
export async function downloadPdf(id: string): Promise<Blob> {
  const url = `${API_BASE}/api/cvs/${id}/pdf`;
  let token: string | null = null;
  if (globalTokenGetter) {
    try {
      token = await globalTokenGetter();
    } catch {
      // Ignored
    }
  }

  const headers: HeadersInit = {};
  if (token) {
    headers["Authorization"] = `Bearer ${token}`;
  }
  if (globalClerkUserId) {
    headers["X-User-Id"] = globalClerkUserId;
  }

  const response = await fetch(url, {
    method: "POST",
    headers,
  });

  if (!response.ok) {
    let errorDetail = `PDF generation failed with status ${response.status}`;
    try {
      const data = await response.json();
      if (data && typeof data === "object") {
        const d = data as { detail?: string; title?: string };
        errorDetail = d.detail || d.title || errorDetail;
      }
    } catch {
      // Not JSON
    }
    throw new ApiError(response.status, errorDetail);
  }

  return await response.blob();
}

/**
 * Triggers a browser download of a Blob file.
 */
export function saveBlobToFile(blob: Blob, filename: string) {
  if (typeof window === "undefined") return;
  const url = window.URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  window.URL.revokeObjectURL(url);
  document.body.removeChild(a);
}

/**
 * Downloads CV as PDF and saves to local file.
 */
export async function downloadCvPdf(id: string, candidateName?: string): Promise<void> {
  const url = `${API_BASE}/api/cvs/${id}/pdf`;
  let token: string | null = null;
  if (globalTokenGetter) {
    try {
      token = await globalTokenGetter();
    } catch {
      // Ignored
    }
  }

  const headers: HeadersInit = {};
  if (token) {
    headers["Authorization"] = `Bearer ${token}`;
  }
  if (globalClerkUserId) {
    headers["X-User-Id"] = globalClerkUserId;
  }

  const response = await fetch(url, {
    method: "POST",
    headers,
  });

  if (!response.ok) {
    let errorDetail = `PDF generation failed with status ${response.status}`;
    try {
      const data = await response.json();
      if (data && typeof data === "object") {
        const d = data as { detail?: string; title?: string };
        errorDetail = d.detail || d.title || errorDetail;
      }
    } catch {
      // Not JSON
    }
    throw new ApiError(response.status, errorDetail);
  }

  // Extract server-specified filename from Content-Disposition header if available
  let filename: string | null = null;
  const disposition = response.headers.get("content-disposition");
  if (disposition && disposition.includes("filename=")) {
    const match = disposition.match(/filename[^;=\n]*=((['"]).*?\2|[^;\n]*)/);
    if (match && match[1]) {
      filename = match[1].replace(/['"]/g, "").trim();
    }
  }

  if (!filename) {
    const slug = (candidateName || "cv")
      .trim()
      .toLowerCase()
      .replace(/\s+/g, "-")
      .replace(/[^a-z0-9-]/g, "");
    filename = `${slug || "cv"}-cv.pdf`;
  }

  const blob = await response.blob();
  saveBlobToFile(blob, filename);
}

